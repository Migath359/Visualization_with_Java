package org.example.demo01;

public class Szemely {
    private String nev;
    private int kor;

    public Szemely(String nev, int kor) {
        this.nev = nev;
        this.kor = kor;
    }

    public String getNev() {
        return nev;
    }

    public int getKor() {
        return kor;
    }

}
